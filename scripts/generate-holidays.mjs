#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(repoRoot, 'src', 'lib', 'holidays.generated.ts');
const countries = ['CN', 'US'];

function getYearRange(anchorYear) {
  const startYear = anchorYear - 1;
  const endYear = anchorYear + 10;
  const years = [];
  for (let year = startYear; year <= endYear; year += 1) years.push(year);
  return years;
}

async function fetchPublicHolidays(year, countryCode) {
  const url = `https://date.nager.at/api/v3/PublicHolidays/${year}/${countryCode}`;
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to fetch ${countryCode} ${year}: ${res.status} ${res.statusText}`);
  }
  const payload = await res.json();
  if (!Array.isArray(payload)) {
    throw new Error(`Unexpected payload for ${countryCode} ${year}`);
  }
  return payload
    .filter((item) => typeof item?.date === 'string' && typeof item?.name === 'string')
    .map((item) => ({ date: item.date, name: item.name }));
}

function stableHolidayMap(holidayMap) {
  return Object.fromEntries(
    Object.entries(holidayMap)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([key, entries]) => {
        const dedup = new Map(entries.map((entry) => [`${entry.date}|${entry.name}`, entry]));
        const sortedEntries = [...dedup.values()].sort((a, b) => {
          if (a.date !== b.date) return a.date.localeCompare(b.date);
          return a.name.localeCompare(b.name);
        });
        return [key, sortedEntries];
      }),
  );
}

function renderGeneratedModule(holidayMap, years) {
  const lines = [];
  lines.push('/**');
  lines.push(' * AUTO-GENERATED FILE — DO NOT EDIT MANUALLY.');
  lines.push(' * Generated by scripts/generate-holidays.mjs');
  lines.push(` * Coverage: ${years[0]}-${years[years.length - 1]} (CN, US)`);
  lines.push(' */');
  lines.push('');
  lines.push('export type GeneratedHolidayEntry = { date: string; name: string };');
  lines.push('export type GeneratedHolidayMap = Record<string, GeneratedHolidayEntry[]>;');
  lines.push('');
  lines.push('export const GENERATED_HOLIDAYS: GeneratedHolidayMap = {');
  for (const [key, entries] of Object.entries(holidayMap)) {
    lines.push(`  "${key}": [`);
    for (const entry of entries) {
      lines.push(`    { date: "${entry.date}", name: ${JSON.stringify(entry.name)} },`);
    }
    lines.push('  ],');
  }
  lines.push('};');
  lines.push('');
  return `${lines.join('\n')}`;
}

async function main() {
  const anchorYear = new Date().getUTCFullYear();
  const years = getYearRange(anchorYear);
  const holidayMap = {};

  for (const year of years) {
    for (const countryCode of countries) {
      const entries = await fetchPublicHolidays(year, countryCode);
      holidayMap[`${year}-${countryCode}`] = entries;
    }
  }

  const stableMap = stableHolidayMap(holidayMap);
  const content = renderGeneratedModule(stableMap, years);
  fs.writeFileSync(outputPath, `${content}\n`, 'utf8');
  console.log(`Generated holiday data at ${path.relative(repoRoot, outputPath)} for ${years[0]}-${years[years.length - 1]}.`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
